#!/bin/sh

set -eu

if [ $# -ne 2 ]; then
    echo "usage: $0 NAME IMAGE" >&2
    exit 1
fi

name=$1
image=$2
script_dir=$(dirname "$0")

echo "// Generated by scripts/oled-image.sh from $image, do not edit."
echo "#pragma once"
echo
echo "static const char PROGMEM $name[] = {"
convert "$image" -compress none pbm:- | awk -f "$script_dir/pbm-to-oled.awk"
echo "};"
